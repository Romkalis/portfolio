function Navigation() {

  const [isMobile, setIsMobile] = useState(false);

  useLayoutEffect(() => {
    const checkIsMobile = () => {
      setIsMobile(window.innerWidth <= 900);
    };
    checkIsMobile();
    window.addEventListener('resize', checkIsMobile);
    return () => window.removeEventListener('resize', checkIsMobile);
  }, []);

  const [isBurgerOpen, setIsBurgerOpen] = useState(false)
  const path = usePathname();
  const burgerHandler = () => {
    setIsBurgerOpen(prev => !prev)
  }
  const isActiveLink = (key: string): boolean => {
    return key === path.replaceAll('/', '')
  }


  return (
    <header className={`${s.header}`}>
      <nav className={`${s.wrapper} `} aria-label="Navigation principale">
        <a
          href={withBase(`/`)} className={s.logo}
          title={`Header: ${sitePreferences.name}`}>
          <img src={withBase("/docs_pic/logos-a5q/logo-a5q.webp")} alt="Logotype Parimaster" width={82}
               height={50}/>
        </a>

        <ul className={isBurgerOpen ? `${s.navList} ${s.navListActive}` : s.navList} aria-label="Liste de navigation">
          {isMobile && <li  className={`${s.navItem}`}>
            <Finder />
          </li>}
          {
            Object.entries(headerLinks).map(([key, {title, svg}]) => (
              <li key={title} className={`${s.navItem}`}>
                <a href={withBase(`/${key}`)} className={`${s.navLink} ${isActiveLink(key) && s.linkActive}`} title={title} aria-label={title}>
                  {svg} {title}
                </a>
              </li>
            ))}
        </ul>

      </nav>

      <div className={s['burger-menu']}>
        <button className={

          isBurgerOpen ? `${s.burger} ${s.active}` : s.burger

        } onClick={burgerHandler} aria-label={'Appuyez sur le bouton Burger pour ouvrir le menu.'}>

          <span></span>
          <span></span>
          <span></span>
        </button>
      </div>

    </header>
  );
}

